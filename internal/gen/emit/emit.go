package emit

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
	"unicode"

	"github.com/otfabric/go-ieee20305/internal/gen/xsd"
)

// Emitter generates Go source files from a resolved XSD schema.
type Emitter struct {
	r       *xsd.Resolved
	outDir  string
	pkgName string
	hash    string // SHA-256 of the source XSD
	source  string // filename of the source XSD
}

// New creates a Go code emitter.
func New(r *xsd.Resolved, outDir, pkgName, source, hash string) *Emitter {
	return &Emitter{
		r:       r,
		outDir:  outDir,
		pkgName: pkgName,
		hash:    hash,
		source:  source,
	}
}

// Emit generates all Go source files.
func (e *Emitter) Emit() error {
	if err := os.MkdirAll(e.outDir, 0o755); err != nil {
		return err
	}
	if err := e.emitTypes(); err != nil {
		return fmt.Errorf("emit types_gen.go: %w", err)
	}
	if err := e.emitPrimitives(); err != nil {
		return fmt.Errorf("emit primitives_gen.go: %w", err)
	}
	if err := e.emitXML(); err != nil {
		return fmt.Errorf("emit xml_gen.go: %w", err)
	}
	return nil
}

func (e *Emitter) header() string {
	return fmt.Sprintf(`// SPDX-License-Identifier: MIT

// Code generated by ieee20305-gen from %s (SHA-256: %s); DO NOT EDIT.
`, e.source, e.hash)
}

func (e *Emitter) writeFile(name, content string) error {
	formatted, err := format.Source([]byte(content))
	if err != nil {
		path := filepath.Join(e.outDir, name)
		_ = os.WriteFile(path, []byte(content), 0o644)
		return fmt.Errorf("gofmt %s: %w", name, err)
	}
	path := filepath.Join(e.outDir, name)
	return os.WriteFile(path, formatted, 0o644)
}

// --- Naming helpers ---

// GoTypeName converts an XSD type name to an exported Go type name.
func GoTypeName(xsdName string) string {
	return exportName(xsdName)
}

func goFieldName(xmlName string) string {
	return exportName(xmlName)
}

func exportName(s string) string {
	if s == "" {
		return s
	}
	r := strings.NewReplacer(
		"-", "_",
		".", "_",
		"/", "_",
		" ", "_",
	)
	s = r.Replace(s)

	runes := []rune(s)
	runes[0] = unicode.ToUpper(runes[0])
	return string(runes)
}

func goEnumConstName(typeName, value string) string {
	var b strings.Builder
	for _, r := range value {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9':
			b.WriteRune(r)
		case r == '_':
			b.WriteRune(r)
		case r == '-', r == '.', r == '/', r == ' ':
			b.WriteRune('_')
		default:
		}
	}
	clean := b.String()
	for strings.Contains(clean, "__") {
		clean = strings.ReplaceAll(clean, "__", "_")
	}
	clean = strings.Trim(clean, "_")
	if clean == "" {
		clean = "Unknown"
	}
	if len(clean) > 0 && clean[0] >= '0' && clean[0] <= '9' {
		clean = "V" + clean
	}
	return typeName + clean
}

// XSDToGoType maps an XSD builtin type to a Go type.
func XSDToGoType(xsdType string) string {
	switch xsdType {
	case "xs:string", "xs:normalizedString", "xs:token", "xs:anyURI":
		return "string"
	case "xs:boolean":
		return "bool"
	case "xs:integer", "xs:int":
		return "int32"
	case "xs:unsignedInt":
		return "uint32"
	case "xs:unsignedByte":
		return "uint8"
	case "xs:unsignedShort":
		return "uint16"
	case "xs:short":
		return "int16"
	case "xs:long":
		return "int64"
	case "xs:unsignedLong":
		return "uint64"
	case "xs:hexBinary":
		return "[]byte"
	case "xs:positiveInteger", "xs:nonNegativeInteger":
		return "int64"
	default:
		return "string"
	}
}
