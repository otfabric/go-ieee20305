package emit

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/otfabric/go-ieee20305/internal/gen/xsd"
)

// ExtensionEmitter generates Go source files for an extension schema
// (e.g. CSIP-AUS) in a separate package that imports the base package.
type ExtensionEmitter struct {
	re         *xsd.ResolvedExtension
	outDir     string
	pkgName    string    // e.g. "csipaus"
	basePkg    string    // e.g. "github.com/otfabric/go-ieee20305"
	baseImport string    // e.g. "ieee20305"
	hash       string
	source     string
}

// NewExtension creates an extension emitter.
func NewExtension(re *xsd.ResolvedExtension, outDir, pkgName, basePkg, baseImport, source, hash string) *ExtensionEmitter {
	return &ExtensionEmitter{
		re:         re,
		outDir:     outDir,
		pkgName:    pkgName,
		basePkg:    basePkg,
		baseImport: baseImport,
		hash:       hash,
		source:     source,
	}
}

// Emit generates extension Go source files.
func (e *ExtensionEmitter) Emit() error {
	if err := os.MkdirAll(e.outDir, 0o755); err != nil {
		return err
	}
	if err := e.emitTypes(); err != nil {
		return fmt.Errorf("emit types_gen.go: %w", err)
	}
	if err := e.emitPrimitives(); err != nil {
		return fmt.Errorf("emit primitives_gen.go: %w", err)
	}
	if err := e.emitXML(); err != nil {
		return fmt.Errorf("emit xml_gen.go: %w", err)
	}
	return nil
}

func (e *ExtensionEmitter) header() string {
	return fmt.Sprintf(`// SPDX-License-Identifier: MIT

// Code generated by ieee20305-gen from %s (SHA-256: %s); DO NOT EDIT.
`, e.source, e.hash)
}

func (e *ExtensionEmitter) isExtensionType(name string) bool {
	return !e.re.BaseTypeNames[name]
}

func (e *ExtensionEmitter) emitTypes() error {
	// Collect extension-only complex types.
	var extTypes []*xsd.ComplexType
	for _, ct := range e.re.ComplexTypes {
		if ct.Name == "" || ct.Abstract {
			continue
		}
		if e.isExtensionType(ct.Name) {
			extTypes = append(extTypes, ct)
		}
	}

	if len(extTypes) == 0 {
		return nil
	}

	sort.Slice(extTypes, func(i, j int) bool {
		return extTypes[i].Name < extTypes[j].Name
	})

	var b strings.Builder
	b.WriteString(e.header())
	fmt.Fprintf(&b, "package %s\n\n", e.pkgName)

	// Import base package.
	fmt.Fprintf(&b, "import (\n")
	fmt.Fprintf(&b, "\t%s %q\n", e.baseImport, e.basePkg)
	fmt.Fprintf(&b, ")\n\n")
	// Ensure import is used.
	fmt.Fprintf(&b, "var _ = %s.UInt32(0)\n\n", e.baseImport)

	for _, ct := range extTypes {
		e.emitComplexType(&b, ct)
	}

	return e.writeFile("types_gen.go", b.String())
}

func (e *ExtensionEmitter) emitComplexType(b *strings.Builder, ct *xsd.ComplexType) {
	typeName := GoTypeName(ct.Name)

	if ct.Doc != "" {
		fmt.Fprintf(b, "// %s is generated from xs:complexType %q.\n//\n// %s\n", typeName, ct.Name, ct.Doc)
	} else {
		fmt.Fprintf(b, "// %s is generated from xs:complexType %q.\n", typeName, ct.Name)
	}

	fmt.Fprintf(b, "type %s struct {\n", typeName)

	// Embed base type — use qualified name if it's a base package type.
	if ct.BaseType != "" && !xsd.IsBuiltinXSD(ct.BaseType) {
		if baseCT, ok := e.re.ComplexTypeMap[ct.BaseType]; ok {
			baseGoName := GoTypeName(ct.BaseType)
			if e.re.BaseTypeNames[ct.BaseType] {
				if baseCT.Abstract {
					e.emitFlattenedFields(b, baseCT, make(map[string]bool))
				} else {
					fmt.Fprintf(b, "\t%s.%s\n", e.baseImport, baseGoName)
				}
			} else {
				if baseCT.Abstract {
					e.emitFlattenedFields(b, baseCT, make(map[string]bool))
				} else {
					fmt.Fprintf(b, "\t%s\n", baseGoName)
				}
			}
		}
	}

	// Own sequence elements.
	seen := make(map[string]bool)
	for _, el := range ct.Sequence {
		name := el.Name
		if el.Ref != "" {
			name = el.Ref
		}
		if seen[name] {
			continue
		}
		seen[name] = true
		e.emitField(b, el)
	}

	// Own attributes.
	for _, attr := range ct.Attributes {
		if attr.Name != "" {
			e.emitAttrField(b, attr)
		}
	}

	fmt.Fprintf(b, "}\n\n")
}

func (e *ExtensionEmitter) emitFlattenedFields(b *strings.Builder, ct *xsd.ComplexType, seen map[string]bool) {
	if ct.BaseType != "" && !xsd.IsBuiltinXSD(ct.BaseType) {
		if base, ok := e.re.ComplexTypeMap[ct.BaseType]; ok {
			if base.Abstract {
				e.emitFlattenedFields(b, base, seen)
			} else {
				baseGoName := GoTypeName(ct.BaseType)
				if e.re.BaseTypeNames[ct.BaseType] {
					fmt.Fprintf(b, "\t%s.%s\n", e.baseImport, baseGoName)
				} else {
					fmt.Fprintf(b, "\t%s\n", baseGoName)
				}
			}
		}
	}

	for _, el := range ct.Sequence {
		name := el.Name
		if el.Ref != "" {
			name = el.Ref
		}
		if seen[name] {
			continue
		}
		seen[name] = true
		e.emitField(b, el)
	}

	for _, attr := range ct.Attributes {
		if attr.Name != "" && !seen[attr.Name] {
			seen[attr.Name] = true
			e.emitAttrField(b, attr)
		}
	}
}

func (e *ExtensionEmitter) emitField(b *strings.Builder, el *xsd.Element) {
	fieldName := el.Name
	if el.Ref != "" {
		fieldName = el.Ref
	}
	goName := goFieldName(fieldName)
	typeName := e.resolveElementType(el)
	tag := fieldName

	isSlice := el.MaxOccurs == -1 || el.MaxOccurs > 1
	isOptional := el.MinOccurs == 0 && !isSlice

	var goType string
	switch {
	case isSlice:
		goType = "[]" + typeName
	case isOptional:
		goType = "*" + typeName
	default:
		goType = typeName
	}

	omit := ""
	if el.MinOccurs == 0 {
		omit = ",omitempty"
	}

	fmt.Fprintf(b, "\t%s %s `xml:\"%s%s\"`\n", goName, goType, tag, omit)
}

func (e *ExtensionEmitter) emitAttrField(b *strings.Builder, attr *xsd.Attribute) {
	goName := goFieldName(attr.Name)
	goType := e.resolveAttrType(attr)
	omit := ""
	if attr.Use != "required" {
		omit = ",omitempty"
	}
	fmt.Fprintf(b, "\t%s %s `xml:\"%s,attr%s\"`\n", goName, goType, attr.Name, omit)
}

func (e *ExtensionEmitter) resolveElementType(el *xsd.Element) string {
	typeName := el.Type
	if typeName == "" && el.Ref != "" {
		if refEl, ok := e.re.ElementMap[el.Ref]; ok {
			typeName = refEl.Type
		}
	}
	if typeName == "" {
		return "string"
	}
	if xsd.IsBuiltinXSD(typeName) {
		return XSDToGoType(typeName)
	}
	if _, ok := e.re.ComplexTypeMap[typeName]; ok {
		goName := GoTypeName(typeName)
		if e.re.BaseTypeNames[typeName] {
			return e.baseImport + "." + goName
		}
		return goName
	}
	if _, ok := e.re.SimpleTypeMap[typeName]; ok {
		goName := GoTypeName(typeName)
		if e.re.BaseTypeNames[typeName] {
			return e.baseImport + "." + goName
		}
		return goName
	}
	return "string"
}

func (e *ExtensionEmitter) resolveAttrType(attr *xsd.Attribute) string {
	if attr.InlineSimple != nil {
		if attr.InlineSimple.IsEnum() {
			return "string"
		}
		if attr.InlineSimple.Base != "" {
			return XSDToGoType(attr.InlineSimple.Base)
		}
		return "string"
	}
	if attr.Type == "" {
		return "string"
	}
	if xsd.IsBuiltinXSD(attr.Type) {
		return XSDToGoType(attr.Type)
	}
	if _, ok := e.re.SimpleTypeMap[attr.Type]; ok {
		goName := GoTypeName(attr.Type)
		if e.re.BaseTypeNames[attr.Type] {
			return e.baseImport + "." + goName
		}
		return goName
	}
	return "string"
}

func (e *ExtensionEmitter) emitPrimitives() error {
	var enums []*xsd.SimpleType
	var aliases []*xsd.SimpleType
	for _, st := range e.re.SimpleTypes {
		if st.Name == "" || e.re.BaseTypeNames[st.Name] {
			continue
		}
		if st.IsEnum() {
			enums = append(enums, st)
		} else {
			aliases = append(aliases, st)
		}
	}

	if len(enums) == 0 && len(aliases) == 0 {
		return nil
	}

	sort.Slice(aliases, func(i, j int) bool { return aliases[i].Name < aliases[j].Name })
	sort.Slice(enums, func(i, j int) bool { return enums[i].Name < enums[j].Name })

	var b strings.Builder
	b.WriteString(e.header())
	fmt.Fprintf(&b, "package %s\n", e.pkgName)

	if len(aliases) > 0 {
		b.WriteString("\n// --- Primitive types ---\n\n")
		for _, st := range aliases {
			typeName := GoTypeName(st.Name)
			goBase := resolveSimpleBase(st)
			fmt.Fprintf(&b, "// %s is generated from xs:simpleType %q.\n", typeName, st.Name)
			fmt.Fprintf(&b, "type %s %s\n\n", typeName, goBase)
		}
	}

	if len(enums) > 0 {
		b.WriteString("\n// --- Enumeration types ---\n\n")
		for _, st := range enums {
			typeName := GoTypeName(st.Name)
			fmt.Fprintf(&b, "// %s is generated from xs:simpleType %q.\n", typeName, st.Name)
			fmt.Fprintf(&b, "type %s string\n\n", typeName)
			fmt.Fprintf(&b, "const (\n")
			usedConsts := make(map[string]int)
			for _, val := range st.Enumerations {
				constName := goEnumConstName(typeName, val)
				if n, dup := usedConsts[constName]; dup {
					usedConsts[constName] = n + 1
					constName = fmt.Sprintf("%s_%d", constName, n+1)
				} else {
					usedConsts[constName] = 1
				}
				fmt.Fprintf(&b, "\t%s %s = %q\n", constName, typeName, val)
			}
			fmt.Fprintf(&b, ")\n\n")
		}
	}

	return e.writeFile("primitives_gen.go", b.String())
}

func (e *ExtensionEmitter) emitXML() error {
	var hexTypes []hexBinaryInfo

	for _, st := range e.re.SimpleTypes {
		if st.Name == "" || e.re.BaseTypeNames[st.Name] {
			continue
		}
		if st.Base == "xs:hexBinary" && st.MinLength > 0 && st.MinLength == st.MaxLength {
			hexTypes = append(hexTypes, hexBinaryInfo{
				GoName: GoTypeName(st.Name),
				Len:    st.MinLength,
			})
		}
	}

	if len(hexTypes) == 0 {
		return nil
	}

	var b strings.Builder
	b.WriteString(e.header())
	fmt.Fprintf(&b, "package %s\n\n", e.pkgName)
	b.WriteString("import (\n")
	b.WriteString("\t\"encoding/hex\"\n")
	b.WriteString("\t\"encoding/xml\"\n")
	b.WriteString("\t\"fmt\"\n")
	b.WriteString("\t\"strings\"\n")
	b.WriteString(")\n\n")

	for _, h := range hexTypes {
		emitHexBinaryMethods(&b, h)
	}

	return e.writeFile("xml_gen.go", b.String())
}

func (e *ExtensionEmitter) writeFile(name, content string) error {
	formatted, err := format.Source([]byte(content))
	if err != nil {
		path := filepath.Join(e.outDir, name)
		_ = os.WriteFile(path, []byte(content), 0o644)
		return fmt.Errorf("gofmt %s: %w", name, err)
	}
	path := filepath.Join(e.outDir, name)
	return os.WriteFile(path, formatted, 0o644)
}
