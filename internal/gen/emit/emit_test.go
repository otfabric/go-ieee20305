func TestGeneratedCodeCompilesAndBehaves(t *testing.T) {
	if testing.Short() {
		t.Skip("builds a module")
	}
	goTool, err := exec.LookPath("go")
	if err != nil {
		t.Skip("go tool not found")
	}
	base, profile, baseEx, profileEx := generate(t)
	dir := t.TempDir()
	write := func(rel string, data []byte) {
		p := filepath.Join(dir, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, data, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("go.mod", []byte("module "+module+"\n\ngo 1.23\n"))
	write("support.go", []byte(support))
	write("behaviour_test.go", []byte(behaviour))
	for name, src := range base {
		write(name, src)
	}
	for name, src := range profile {
		write(filepath.Join("profile", name), src)
	}
	for name, src := range baseEx {
		write(filepath.Join("examples", name), src)
	}
	for name, src := range profileEx {
		write(filepath.Join("profile", "examples", name), src)
	}
	cmd := exec.Command(goTool, "test", "-count=1", "./...")
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GOWORK=off", "GOFLAGS=-mod=mod")
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("generated code does not build or behave:\n%s", out)
	}
}
