var update = flag.Bool("update", false, "rewrite the golden files")

const (
	baseNS = "urn:test:base"
	header = "// Code generated by ieee20305-gen; DO NOT EDIT.\n"
	module = "example.test/gen"
)

func b(local string) xsd.QName { return xsd.QName{Space: baseNS, Local: local} }

func fixture(name string) string { return filepath.Join("..", "testdata", name) }

var (
	baseExamples    = &emit.Examples{Package: "examples", ImportPath: module + "/examples"}
	profileExamples = &emit.Examples{Package: "examples", ImportPath: module + "/profile/examples"}
)

// generate produces the fixture base package (with resources and generated
// tests) and profile, and their example builders.
func generate(t *testing.T) (base, profile, baseEx, profileEx emit.Files) {
	t.Helper()
	bs, err := xsd.Load(fixture("base.xsd"), xsd.Options{})
	if err != nil {
		t.Fatal(err)
	}
	baseCfg := emit.Config{
		Package:     "base",
		ImportPath:  module,
		Header:      header,
		Polymorphic: map[xsd.QName]map[string]bool{b("Notification"): {"Resource": true}},
		Examples:    baseExamples,
	}
	base, err = emit.Generate(bs, baseCfg)
	if err != nil {
		t.Fatal(err)
	}
	if baseEx, err = emit.GenerateExamples(bs, baseCfg); err != nil {
		t.Fatal(err)
	}
	app, err := wadl.ParseFile(fixture("app.wadl"))
	if err != nil {
		t.Fatal(err)
	}
	if base["resources_gen.go"], err = emit.Resources(app, bs, "base", header); err != nil {
		t.Fatal(err)
	}
	ps, err := xsd.Load(fixture("core.xsd"), xsd.Options{ElementRefs: map[xsd.QName]xsd.LocalElement{
		b("Missing"): {Name: b("Missing"), Type: b("Link")},
	}})
	if err != nil {
		t.Fatal(err)
	}
	profileCfg := emit.Config{
		Package:        "profile",
		ImportPath:     module + "/profile",
		Header:         header,
		ProfileVersion: "9.9",
		Base:           &emit.Base{Package: "base", ImportPath: module, Set: bs, Examples: baseExamples},
		Examples:       profileExamples,
	}
	profile, err = emit.Generate(ps, profileCfg)
	if err != nil {
		t.Fatal(err)
	}
	if profileEx, err = emit.GenerateExamples(ps, profileCfg); err != nil {
		t.Fatal(err)
	}
	return base, profile, baseEx, profileEx
}

func TestGolden(t *testing.T) {
	base, profile, baseEx, profileEx := generate(t)
	for dir, files := range map[string]emit.Files{"base": base, "profile": profile, "base-examples": baseEx, "profile-examples": profileEx} {
		goldenDir := filepath.Join("testdata", "golden", dir)
		if *update {
			if err := os.RemoveAll(goldenDir); err != nil {
				t.Fatal(err)
			}
			if err := os.MkdirAll(goldenDir, 0o755); err != nil {
				t.Fatal(err)
			}
		}
		for name, src := range files {
			path := filepath.Join(goldenDir, name+".golden")
			if *update {
				if err := os.WriteFile(path, src, 0o644); err != nil {
					t.Fatal(err)
				}
				continue
			}
			want, err := os.ReadFile(path)
			if err != nil {
				t.Fatalf("%v (run go test -update)", err)
			}
			if !bytes.Equal(src, want) {
				t.Errorf("%s/%s differs from its golden file; run go test ./internal/gen/emit -update and review the diff", dir, name)
			}
		}
		entries, _ := os.ReadDir(goldenDir)
		if len(entries) != len(files) {
			t.Errorf("%s: %d golden files for %d generated files", dir, len(entries), len(files))
		}
	}
}

func TestDeterministic(t *testing.T) {
	a, ap, ae, ape := generate(t)
	b, bp, be, bpe := generate(t)
	for _, pair := range []struct {
		what string
		x, y emit.Files
	}{{"base", a, b}, {"profile", ap, bp}, {"base examples", ae, be}, {"profile examples", ape, bpe}} {
		for name := range pair.x {
			if !bytes.Equal(pair.x[name], pair.y[name]) {
				t.Errorf("%s %s differs between runs", pair.what, name)
			}
		}
	}
}

func TestProfileOwnership(t *testing.T) {
	_, profile, _, _ := generate(t)
	src := string(profile["types_gen.go"])
	var types []string
	for _, line := range strings.Split(src, "\n") {
		if strings.HasPrefix(line, "type ") {
			types = append(types, strings.Fields(line)[1])
		}
	}
	sort.Strings(types)
	// Control and Link are redefined; Device contains both, DeviceList
	// contains Device; MeterType is the profile's own. Notification, Power
	// and Resource are unchanged and stay in base.
	if got, want := strings.Join(types, " "), "Control Device DeviceList Link MeterType"; got != want {
		t.Errorf("profile types = %s, want %s", got, want)
	}
	if !strings.Contains(string(profile["scalars_gen.go"]), "type ModeType []byte") {
		t.Error("the profile's simple-content ModeType is a scalar")
	}
	for _, want := range []string{
		"type Control struct {\n\tbase.Control\n",
		"type Device struct {\n\tbase.Resource\n",
		"Control *Control `xml:\"urn:test:base Control,omitempty\"`",
		"Link []Link `xml:\"urn:test:base Link,omitempty\"`",
		"LimitExtra *base.Power `xml:\"urn:test:ext limitExtra,omitempty\"`",
		// Link is redefined, so references to it use the profile's Link.
		"Missing *Link `xml:\"urn:test:base Missing,omitempty\"`",
	} {
		if !strings.Contains(strings.Join(strings.Fields(src), " "), strings.Join(strings.Fields(want), " ")) {
			t.Errorf("profile types_gen.go lacks %q", want)
		}
	}
	elems := string(profile["elements_gen.go"])
	for _, want := range []string{`Local: "Device"`, `Local: "DeviceList"`, `Local: "Meter"`, `const Namespace = "urn:test:ext"`, `const ProfileVersion = "9.9"`} {
		if !strings.Contains(elems, want) {
			t.Errorf("profile elements_gen.go lacks %s", want)
		}
	}
	for _, unwanted := range []string{`"limitExtra"`, `"Notification"`} {
		if strings.Contains(elems, unwanted) {
			t.Errorf("profile elements_gen.go must not list %s", unwanted)
		}
	}
}

func TestGenerateErrors(t *testing.T) {
	bs, err := xsd.Load(fixture("base.xsd"), xsd.Options{})
	if err != nil {
		t.Fatal(err)
	}
	for name, poly := range map[string]map[xsd.QName]map[string]bool{
		"unknown owner":   {b("Nope"): {"Resource": true}},
		"unknown element": {b("Notification"): {"Nope": true}},
		"scalar element":  {b("Device"): {"sFDI": true}},
	} {
		if _, err := emit.Generate(bs, emit.Config{Package: "base", Header: header, Polymorphic: poly}); err == nil {
			t.Errorf("%s: Generate succeeded", name)
		}
	}
}

