package emit

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"

	"github.com/otfabric/go-ieee20305/internal/gen/wadl"
)

// ResourceEmitter generates a Go resource table from a parsed WADL.
type ResourceEmitter struct {
	app     *wadl.Application
	outDir  string
	pkgName string
	source  string
	hash    string
}

// NewResourceEmitter creates a resource emitter.
func NewResourceEmitter(app *wadl.Application, outDir, pkgName, source, hash string) *ResourceEmitter {
	return &ResourceEmitter{
		app:     app,
		outDir:  outDir,
		pkgName: pkgName,
		source:  source,
		hash:    hash,
	}
}

// Emit writes resources_gen.go to the output directory.
func (e *ResourceEmitter) Emit() error {
	flat := e.app.Flatten()
	if len(flat) == 0 {
		return nil
	}

	sort.Slice(flat, func(i, j int) bool {
		return flat[i].Path < flat[j].Path
	})

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// SPDX-License-Identifier: MIT\n\n")
	fmt.Fprintf(&buf, "// Code generated by ieee20305-gen from %s (SHA-256: %s); DO NOT EDIT.\n\n", e.source, e.hash)
	fmt.Fprintf(&buf, "package %s\n\n", e.pkgName)

	e.emitTypes(&buf)
	e.emitTable(&buf, flat)

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("gofmt resources: %w", err)
	}

	return os.WriteFile(filepath.Join(e.outDir, "resources_gen.go"), formatted, 0o644)
}

func (e *ResourceEmitter) emitTypes(buf *bytes.Buffer) {
	fmt.Fprintf(buf, "// ResourceMethod describes an HTTP method supported on a resource.\n")
	fmt.Fprintf(buf, "type ResourceMethod struct {\n")
	fmt.Fprintf(buf, "\tMethod string\n")
	fmt.Fprintf(buf, "\tRequestType string\n")
	fmt.Fprintf(buf, "\tResponseType string\n")
	fmt.Fprintf(buf, "}\n\n")

	fmt.Fprintf(buf, "// Resource describes a REST resource from the WADL.\n")
	fmt.Fprintf(buf, "type Resource struct {\n")
	fmt.Fprintf(buf, "\tPath string\n")
	fmt.Fprintf(buf, "\tMethods []ResourceMethod\n")
	fmt.Fprintf(buf, "}\n\n")
}

func (e *ResourceEmitter) emitTable(buf *bytes.Buffer, flat []wadl.FlatResource) {
	fmt.Fprintf(buf, "// Resources is the complete list of REST resources defined by the\n")
	fmt.Fprintf(buf, "// IEEE 2030.5 WADL, sorted by path.\n")
	fmt.Fprintf(buf, "var Resources = []Resource{\n")
	for _, fr := range flat {
		fmt.Fprintf(buf, "\t{Path: %q, Methods: []ResourceMethod{", fr.Path)
		for i, m := range fr.Methods {
			if i > 0 {
				buf.WriteString(", ")
			}
			req := ""
			if m.Request != nil {
				req = m.Request.Element
			}
			resp := ""
			if m.Response != nil {
				resp = m.Response.Element
			}
			fmt.Fprintf(buf, "{Method: %q, RequestType: %q, ResponseType: %q}", m.Name, req, resp)
		}
		fmt.Fprintf(buf, "}},\n")
	}
	fmt.Fprintf(buf, "}\n\n")

	// Emit a lookup helper.
	fmt.Fprintf(buf, "// ResourceByPath returns the Resource for the given path pattern,\n")
	fmt.Fprintf(buf, "// or nil if no resource matches.\n")
	fmt.Fprintf(buf, "func ResourceByPath(path string) *Resource {\n")
	fmt.Fprintf(buf, "\tidx, ok := resourceIndex[path]\n")
	fmt.Fprintf(buf, "\tif !ok {\n")
	fmt.Fprintf(buf, "\t\treturn nil\n")
	fmt.Fprintf(buf, "\t}\n")
	fmt.Fprintf(buf, "\treturn &Resources[idx]\n")
	fmt.Fprintf(buf, "}\n\n")

	fmt.Fprintf(buf, "var resourceIndex = map[string]int{\n")
	for i, fr := range flat {
		fmt.Fprintf(buf, "\t%q: %d,\n", fr.Path, i)
	}
	fmt.Fprintf(buf, "}\n")
}

