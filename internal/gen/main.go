// Command ieee20305-gen generates the Go types of go-ieee20305 from the
// upstream IEEE 2030.5 and CSIP-AUS schemas pinned in schemas/manifest.json.
//
// Usage (from the module root):
//
//	go run ./internal/gen fetch          # download and verify the pinned sources
//	go run ./internal/gen generate       # regenerate every target of the manifest
//	go run ./internal/gen verify         # check generated headers against the manifest, offline
//	go run ./internal/gen check-updates  # report upstream changes and new releases
package main

import (
	"bufio"
	"bytes"
	"context"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"

	"github.com/otfabric/go-ieee20305/internal/gen/emit"
	"github.com/otfabric/go-ieee20305/internal/gen/manifest"
	"github.com/otfabric/go-ieee20305/internal/gen/upstream"
	"github.com/otfabric/go-ieee20305/internal/gen/wadl"
	"github.com/otfabric/go-ieee20305/internal/gen/xsd"
)

// marker identifies files written by this generator.
const marker = "// Code generated by ieee20305-gen; DO NOT EDIT."

// exitUpdates is the exit status of check-updates when it found changes;
// other failures exit with 1.
const exitUpdates = 3

func main() {
	if len(os.Args) < 2 {
		usage()
	}
	cmd, args := os.Args[1], os.Args[2:]
	fs := flag.NewFlagSet(cmd, flag.ExitOnError)
	manifestPath := fs.String("manifest", "schemas/manifest.json", "schema manifest")
	upstreamDir := fs.String("upstream", "schemas/upstream", "directory of the downloaded upstream files")
	root := fs.String("root", ".", "module root the target directories are relative to")
	report := fs.String("report", "", "check-updates: also write the Markdown report to this file")
	_ = fs.Parse(args)

	m, err := manifest.Load(*manifestPath)
	if err != nil {
		fail(err)
	}
	switch cmd {
	case "fetch":
		ctx, cancel := context.WithTimeout(context.Background(), 10*time.Minute)
		defer cancel()
		err = upstream.NewClient(m).Fetch(ctx, m, *upstreamDir, os.Stdout)
	case "generate":
		err = generate(m, *upstreamDir, *root)
	case "verify":
		err = verify(m, *root)
	case "check-updates":
		ctx, cancel := context.WithTimeout(context.Background(), 10*time.Minute)
		defer cancel()
		findings := upstream.NewClient(m).CheckUpdates(ctx, m)
		if len(findings) == 0 {
			fmt.Println("All upstream sources match schemas/manifest.json; no new releases found.")
			return
		}
		text := upstream.Report(findings)
		fmt.Print(text)
		if *report != "" {
			if err := os.WriteFile(*report, []byte(text), 0o644); err != nil {
				fail(err)
			}
		}
		os.Exit(exitUpdates)
	default:
		usage()
	}
	if err != nil {
		fail(err)
	}
}

func usage() {
	fmt.Fprintln(os.Stderr, "usage: ieee20305-gen fetch|generate|verify|check-updates [-manifest file] [-upstream dir] [-root dir] [-report file]")
	os.Exit(2)
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "ieee20305-gen:", err)
	os.Exit(1)
}

// inputs returns the upstream files a target is generated from, sorted.
func inputs(t *manifest.Target) []string {
	set := map[string]bool{t.XSD: true}
	if t.WADL != "" {
		set[t.WADL] = true
	}
	for _, loc := range t.SchemaLocations {
		set[loc] = true
	}
	out := make([]string, 0, len(set))
	for in := range set {
		out = append(out, in)
	}
	sort.Strings(out)
	return out
}

func header(m *manifest.Manifest, t *manifest.Target) string {
	var b strings.Builder
	b.WriteString("// SPDX-License-Identifier: MIT\n\n")
	b.WriteString(marker + "\n")
	b.WriteString("//\n// Regenerate with \"make generate\". Fix the generator in internal/gen, or its\n// inputs in schemas/manifest.json, instead of editing this file.\n//\n")
	b.WriteString("// Sources (pinned in schemas/manifest.json):\n")
	for _, in := range inputs(t) {
		fmt.Fprintf(&b, "//\t%s sha256:%s\n", in, m.FileSHA256(in))
	}
	return b.String()
}

func generate(m *manifest.Manifest, upstreamDir, root string) error {
	sets := map[string]*xsd.Set{}
	for i := range m.Targets {
		t := &m.Targets[i]
		for _, in := range inputs(t) {
			data, err := os.ReadFile(filepath.Join(upstreamDir, filepath.FromSlash(in)))
			if err != nil {
				return fmt.Errorf("%s: %w (run make download)", in, err)
			}
			if got := upstream.SHA256(data); got != m.FileSHA256(in) {
				return fmt.Errorf("%s: SHA-256 %s, manifest pins %s (run make download)", in, got, m.FileSHA256(in))
			}
		}
		opts := xsd.Options{Locations: map[string]string{}, ElementRefs: map[xsd.QName]xsd.LocalElement{}}
		for loc, rel := range t.SchemaLocations {
			opts.Locations[loc] = filepath.Join(upstreamDir, filepath.FromSlash(rel))
		}
		poly := map[xsd.QName]map[string]bool{}
		var extra []emit.ResourceOverride
		for _, o := range t.Overrides {
			if o.Kind == "resource" {
				extra = append(extra, emit.ResourceOverride{ID: o.Name, Like: o.Like, Path: o.Path, Elements: o.Elements})
				continue
			}
			typ, err := xsd.ParseQName(o.Type)
			if err != nil {
				return fmt.Errorf("target %s: override type: %w", t.Name, err)
			}
			switch o.Kind {
			case "elementRef":
				ref, err := xsd.ParseQName(o.Ref)
				if err != nil {
					return fmt.Errorf("target %s: override ref: %w", t.Name, err)
				}
				opts.ElementRefs[ref] = xsd.LocalElement{Name: xsd.QName{Space: ref.Space, Local: o.Name}, Type: typ}
			case "polymorphicElement":
				if poly[typ] == nil {
					poly[typ] = map[string]bool{}
				}
				poly[typ][o.Name] = true
			}
		}
		set, err := xsd.Load(filepath.Join(upstreamDir, filepath.FromSlash(t.XSD)), opts)
		if err != nil {
			return fmt.Errorf("target %s: %w", t.Name, err)
		}
		sets[t.Name] = set
		cfg := emit.Config{Package: t.Package, ImportPath: t.ImportPath, Header: header(m, t), ProfileVersion: t.ProfileVersion, Polymorphic: poly, Examples: examplesOf(t)}
		if t.Base != "" {
			bt, _ := m.Target(t.Base)
			cfg.Base = &emit.Base{Package: bt.Package, ImportPath: bt.ImportPath, Set: sets[t.Base], Examples: examplesOf(bt)}
		}
		files, err := emit.Generate(set, cfg)
		if err != nil {
			return fmt.Errorf("target %s: %w", t.Name, err)
		}
		if t.WADL != "" {
			app, err := wadl.ParseFile(filepath.Join(upstreamDir, filepath.FromSlash(t.WADL)))
			if err != nil {
				return fmt.Errorf("target %s: %w", t.Name, err)
			}
			src, err := emit.Resources(app, set, t.Package, cfg.Header, extra...)
			if err != nil {
				return fmt.Errorf("target %s: %w", t.Name, err)
			}
			files["resources_gen.go"] = src
		}
		dir := filepath.Join(root, filepath.FromSlash(t.Dir))
		if err := write(dir, files); err != nil {
			return fmt.Errorf("target %s: %w", t.Name, err)
		}
		fmt.Printf("%-10s %d files in %s\n", t.Name, len(files), dir)
		if t.Examples != nil {
			ex, err := emit.GenerateExamples(set, cfg)
			if err != nil {
				return fmt.Errorf("target %s: examples: %w", t.Name, err)
			}
			exDir := filepath.Join(root, filepath.FromSlash(t.Examples.Dir))
			if err := write(exDir, ex); err != nil {
				return fmt.Errorf("target %s: %w", t.Name, err)
			}
			fmt.Printf("%-10s %d files in %s\n", t.Name, len(ex), exDir)
		}
	}
	return nil
}

// examplesOf returns the examples configuration of t for the emitter, or
// nil.
func examplesOf(t *manifest.Target) *emit.Examples {
	if t.Examples == nil {
		return nil
	}
	return &emit.Examples{Package: t.Examples.Package, ImportPath: t.Examples.ImportPath}
}

// targetDirs returns the directories the generator writes for t.
func targetDirs(t *manifest.Target) []string {
	dirs := []string{t.Dir}
	if t.Examples != nil {
		dirs = append(dirs, t.Examples.Dir)
	}
	return dirs
}

// write replaces the generated files of dir with files, removing files this
// generator wrote earlier that it no longer produces.
func write(dir string, files emit.Files) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	existing, err := generatedFiles(dir)
	if err != nil {
		return err
	}
	for _, name := range existing {
		if _, keep := files[name]; !keep {
			if err := os.Remove(filepath.Join(dir, name)); err != nil {
				return err
			}
		}
	}
	for name, src := range files {
		if err := os.WriteFile(filepath.Join(dir, name), src, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// generatedFiles lists the files of dir that carry the generator's marker.
func generatedFiles(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var out []string
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") {
			continue
		}
		data, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			return nil, err
		}
		if bytes.Contains(data, []byte(marker)) {
			out = append(out, e.Name())
		}
	}
	return out, nil
}

// verify checks, without the upstream files, that every target has
// generated files whose recorded sources match the manifest.
func verify(m *manifest.Manifest, root string) error {
	for i := range m.Targets {
		t := &m.Targets[i]
		want := map[string]string{}
		for _, in := range inputs(t) {
			want[in] = m.FileSHA256(in)
		}
		total := 0
		for _, rel := range targetDirs(t) {
			n, err := verifyDir(rel, filepath.Join(root, filepath.FromSlash(rel)), want)
			if err != nil {
				return fmt.Errorf("target %s: %w", t.Name, err)
			}
			total += n
		}
		fmt.Printf("%-10s %d generated files match the manifest\n", t.Name, total)
	}
	return nil
}

// verifyDir checks the recorded sources of the generated files of dir and
// returns how many there are.
func verifyDir(rel, dir string, want map[string]string) (int, error) {
	names, err := generatedFiles(dir)
	if err != nil {
		return 0, err
	}
	if len(names) == 0 {
		return 0, fmt.Errorf("no generated files in %s", dir)
	}
	for _, name := range names {
		got, err := recordedSources(filepath.Join(dir, name))
		if err != nil {
			return 0, err
		}
		if len(got) != len(want) {
			return 0, fmt.Errorf("%s/%s: records %d sources, the manifest pins %d; run make generate", rel, name, len(got), len(want))
		}
		for in, sum := range want {
			if got[in] != sum {
				return 0, fmt.Errorf("%s/%s: generated from %s sha256:%s, the manifest pins %s; run make generate", rel, name, in, got[in], sum)
			}
		}
	}
	return len(names), nil
}

func recordedSources(path string) (map[string]string, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer func() { _ = f.Close() }()
	out := map[string]string{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := sc.Text()
		if strings.HasPrefix(line, "package ") {
			break
		}
		rest, ok := strings.CutPrefix(line, "//\t")
		if !ok {
			continue
		}
		in, sum, ok := strings.Cut(rest, " sha256:")
		if ok {
			out[in] = sum
		}
	}
	return out, sc.Err()
}
